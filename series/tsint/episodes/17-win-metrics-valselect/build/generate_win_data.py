#!/usr/bin/env python3
"""Generate data/win.json for episode 17 (sliding windows, metrics, val selection).

Inputs (read-only):
  /root/ts-base/data/episodes/17-win-metrics-valselect/{maotai_hfq.csv,era_metrics.csv,
      horizon_metrics.csv,train_history.csv,forecast_metrics.csv,summary.json}
  /root/ts-base/inventory/evidence/ch3-win-metrics-valselect/ch3-win-metrics-valselect.json

Output: data/win.json (pack-local; gitignored, regenerated by film.json derive).
"""
from __future__ import annotations

import csv
import json
import math
from pathlib import Path

TS = Path("/root/ts-base/data/episodes/17-win-metrics-valselect")
EV = Path("/root/ts-base/inventory/evidence/ch3-win-metrics-valselect/ch3-win-metrics-valselect.json")
OUT = Path(__file__).resolve().parents[1] / "data" / "win.json"

H, F = 96, 24
GAP = 24
LOW_T, HIGH_T = 1500.0, 6000.0


def read_close() -> tuple[list[str], list[float], int]:
    raw = (TS / "maotai_hfq.csv").read_bytes()
    rows = list(csv.reader(raw.decode().splitlines()))
    header, body = rows[0], rows[1:]
    dates = [r[0] for r in body]
    close = [float(r[1]) for r in body]
    return dates, close, len(raw)


def read_csv(name: str) -> list[dict[str, str]]:
    with (TS / name).open() as fh:
        return list(csv.DictReader(fh))


def windows(close: list[float]):
    for i in range(len(close) - H - F + 1):
        yield i, close[i : i + H], close[i + H : i + H + F]


def window_stats(close: list[float]):
    out = []
    for start, x, y in windows(close):
        p = [x[-1]] * F
        n = len(y)
        mae = sum(abs(a - b) for a, b in zip(y, p)) / n
        mape_vals = [100.0 * abs(a - b) / a for a, b in zip(y, p) if a != 0]
        mape = sum(mape_vals) / len(mape_vals) if mape_vals else 0.0
        mean_y = sum(y) / n
        out.append((start, mean_y, mae, mape))
    return out


def hist(values: list[float], lo: float, hi: float, bins: int) -> list[int]:
    counts = [0] * bins
    step = (hi - lo) / bins
    for v in values:
        if v < lo or v >= hi:
            continue
        counts[min(bins - 1, int((v - lo) / step))] += 1
    return counts


def pct(counts: list[int]) -> list[float]:
    total = sum(counts) or 1
    return [round(100.0 * c / total, 3) for c in counts]


def main() -> None:
    dates, close, csv_bytes = read_close()
    ev = json.loads(EV.read_text())
    summary = json.loads((TS / "summary.json").read_text())
    era_rows = {r["era"]: r for r in read_csv("era_metrics.csv")}
    horizon_rows = read_csv("horizon_metrics.csv")
    history = [dict(row) for row in read_csv("train_history.csv")]
    forecast = {(r["candidate"], r["split"]): r for r in read_csv("forecast_metrics.csv")}

    stats = window_stats(close)
    low = [(s, m, a, p) for (s, m, a, p) in stats if m < LOW_T]
    high = [(s, m, a, p) for (s, m, a, p) in stats if m > HIGH_T]

    win = json.loads(json.dumps(summary["windows"]))
    era = json.loads(json.dumps(summary["era"]))
    training = json.loads(json.dumps(summary["training"]))
    syn = json.loads(json.dumps(summary["synthetic"]))
    zero = json.loads(json.dumps(summary["zero"]))
    # summary 里 Infinity 被写成 null，这里改成显式的字符串标记。
    zero["raw"] = "Inf"
    zero["skipCount"] = int(zero["skipCount"])

    # 价格路径：每 4 个交易取一点，保留首末，用于 LinePlot。
    idx = list(range(0, len(close), 4))
    if idx[-1] != len(close) - 1:
        idx.append(len(close) - 1)
    path = {
        "dates": [dates[i] for i in idx],
        "close": [round(close[i], 3) for i in idx],
        "lowT": LOW_T,
        "highT": HIGH_T,
        "lowFirst": min(s for s, m, _, _ in low) if low else 0,
        "lowLast": max(s for s, m, _, _ in low) if low else 0,
        "highFirst": min(s for s, m, _, _ in high) if high else 0,
        "highLast": max(s for s, m, _, _ in high) if high else 0,
    }

    hz: dict[str, dict[str, list[float]]] = {}
    for row in horizon_rows:
        e = row["era"]
        hz.setdefault(e, {"h": [], "mae": [], "mape": []})
        hz[e]["h"].append(int(row["horizon"]) + 1)
        hz[e]["mae"].append(round(float(row["mae"]), 4))
        hz[e]["mape"].append(round(float(row["mape"]), 4))

    mae_bins = [i * 100.0 for i in range(21)]
    mape_bins = [i * 1.0 for i in range(21)]
    hists = {
        "maeEdges": mae_bins,
        "mapeEdges": mape_bins,
        "lowMae": pct(hist([a for (_, _, a, _) in low], 0.0, 2000.0, 20)),
        "highMae": pct(hist([a for (_, _, a, _) in high], 0.0, 2000.0, 20)),
        "lowMape": pct(hist([p for (_, _, _, p) in low], 0.0, 20.0, 20)),
        "highMape": pct(hist([p for (_, _, _, p) in high], 0.0, 20.0, 20)),
    }

    ev_tests = len(ev["tests"])
    ev_ok = sum(1 for t in ev["tests"] if t["ok"])
    data = {
        "meta": {
            "episode": "17-win-metrics-valselect",
            "bookPages": "p.41-44",
            "tsBaseCommit": summary["meta"]["tsBaseCommit"],
            "evidenceCommit": "2229df0",
            "dataCommit": "5e63b2f",
            "runAt": summary["meta"]["runAt"],
            "checks": {"total": ev_tests, "ok": ev_ok},
            "tests": {"suites": 64, "asserts": 945, "window": 10, "metrics": 12, "trainloss": 6},
        },
        "data": {
            "rows": len(close),
            "first": dates[0],
            "last": dates[-1],
            "csvBytes": csv_bytes,
            "minClose": round(min(close), 3),
            "maxClose": round(max(close), 3),
        },
        "windows": {
            "total": win["total"],
            "train": win["train"],
            "val": win["val"],
            "test": win["test"],
            "ranges": win["ranges"],
            "noLeak": win["noLeak"],
            "h": H,
            "f": F,
            "gap": GAP,
        },
        "era": {
            "low": {
                "windows": int(era_rows["low"]["windows"]),
                "mean": round(float(era_rows["low"]["mean_price"]), 3),
                "mae": round(float(era_rows["low"]["mae"]), 4),
                "rmse": round(float(era_rows["low"]["rmse"]), 4),
                "mape": round(float(era_rows["low"]["mape"]), 4),
            },
            "high": {
                "windows": int(era_rows["high"]["windows"]),
                "mean": round(float(era_rows["high"]["mean_price"]), 3),
                "mae": round(float(era_rows["high"]["mae"]), 4),
                "rmse": round(float(era_rows["high"]["rmse"]), 4),
                "mape": round(float(era_rows["high"]["mape"]), 4),
            },
            "maeRatio": round(float(era["maeRatio"]), 4),
            "mapeRatio": round(float(era["mapeRatio"]), 4),
        },
        "path": path,
        "horizon": hz,
        "hist": hists,
        "synthetic": {
            "add5Mae": round(float(forecast[("add5", "all")]["mae"]), 4),
            "add5Mape": round(float(forecast[("add5", "all")]["mape"]), 4),
            "mul102Mae": round(float(forecast[("mul102", "all")]["mae"]), 4),
            "mul102Mape": round(float(forecast[("mul102", "all")]["mape"]), 4),
            "valAdd5Mape": round(float(forecast[("add5", "val")]["mape"]), 4),
            "valMul102Mape": round(float(forecast[("mul102", "val")]["mape"]), 4),
            "maePick": syn["maePick"],
            "mapePick": syn["mapePick"],
            "n": 400,
        },
        "zero": {
            "raw": zero["raw"],
            "skip": round(float(zero["skip"]), 4),
            "skipCount": zero["skipCount"],
            "eps": round(float(zero["eps"]), 2),
        },
        "training": {
            "gradRelErr": training["gradRelErr"],
            "earlyStopBest": training["earlyStopBest"],
            "earlyStopStopped": training["earlyStopStopped"],
            "epochsRun": training["epochsRun"],
            "bestEpoch": training["bestEpoch"],
            "params": training["params"],
            "curve": [
                {
                    "epoch": int(r["epoch"]),
                    "train": round(float(r["train"]), 6),
                    "val": round(float(r["val"]), 6),
                }
                for r in history
            ],
        },
    }

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(data, ensure_ascii=False, separators=(",", ":")) + "\n")
    print(f"wrote {OUT} ({OUT.stat().st_size} bytes)")
    print("windows", data["windows"])
    print("era", data["era"]["low"], data["era"]["high"], data["era"]["maeRatio"], data["era"]["mapeRatio"])
    print("hist", {k: (len(v) if isinstance(v, list) else v) for k, v in hists.items()})
    print("low windows", len(low), "high windows", len(high))


if __name__ == "__main__":
    main()
